CREATE TABLE EMP (
    EMP_ID NUMBER(3),
    FIRST_NAME VARCHAR2(20),
    LAST_NAME VARCHAR2(20),
    HIRE_DATE DATE,
    JOB_ID VARCHAR2(15),
    SAL NUMBER(8),
    DEPT_ID NUMBER(3),

    CONSTRAINT PK_EMP PRIMARY KEY (EMP_ID),
    CONSTRAINT CK_EMP_SAL CHECK (SAL > 0),
    CONSTRAINT CK_EMP_DEPT CHECK (DEPT_ID IN (10,20,30,40,50,60,90,100))
);
CREATE TABLE Cultural_Stud (
    Roll NUMBER(3),
    Name VARCHAR2(20),
    Dept VARCHAR2(5),
    Cul_Fees NUMBER(6),

    CONSTRAINT PK_CULTURAL PRIMARY KEY (Roll),
    CONSTRAINT CK_CULTURAL_DEPT CHECK (Dept IN ('IT','CS')),
    CONSTRAINT CK_CULTURAL_FEE CHECK (Cul_Fees >= 600),
    CONSTRAINT UK_CULTURAL_NAME UNIQUE (Name)
);
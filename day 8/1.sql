CREATE TABLE Sports_Stud (
    Roll NUMBER(3),
    Name VARCHAR2(20),
    Dept VARCHAR2(5),
    Sports_Fee NUMBER(6),

    CONSTRAINT PK_SPORTS PRIMARY KEY (Roll),
    CONSTRAINT CK_SPORTS_DEPT CHECK (Dept IN ('IT','CS')),
    CONSTRAINT CK_SPORTS_FEE CHECK (Sports_Fee >= 1000),
    CONSTRAINT UK_SPORTS_NAME UNIQUE (Name)
);